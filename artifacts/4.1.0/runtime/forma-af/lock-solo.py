#!/usr/bin/env python3
"""lock-solo.py: keep in pnpm-lock.yaml only the changes of the packages you add.

Run from the repository root that holds pnpm-lock.yaml:

  python3 lock-solo.py --antes <package>...   before `pnpm add`: refuses a dirty lock, saves its baseline
  pnpm --dir <app> add -E <package>@<version>
  python3 lock-solo.py <package>...           proposal: prints the reduced diff, writes nothing
  python3 lock-solo.py --write <package>...   writes it, then `pnpm install --offline --frozen-lockfile`;
                                              if that fails, puts back the bytes `pnpm add` generated

A heuristic: a replaced block of the same length that names none of the packages goes back to the baseline
(an unrelated rewrite such as a new workerd resolution). It does not attribute transitive dependencies and does
not guarantee a correct dependency: review the proposal; a doubtful diff goes back with the lock left intact.
"""
import difflib
import pathlib
import subprocess
import sys

LOCK = pathlib.Path('pnpm-lock.yaml')


def fail(message):
    print(message, file=sys.stderr)
    sys.exit(1)


def git(*args):
    return subprocess.run(['git', *args], capture_output=True, check=True, stdin=subprocess.DEVNULL).stdout


args = sys.argv[1:]
mode = args.pop(0) if args and args[0] in ('--antes', '--write') else None
packages = [a for a in args if a]
if not packages or any(p.startswith('-') for p in packages):
    fail('Usage: lock-solo.py [--antes|--write] <package>...  (at least one package)')
if not LOCK.is_file():
    fail('No pnpm-lock.yaml here: run from the repository root')
git_dir = pathlib.Path(git('rev-parse', '--absolute-git-dir').decode().strip())
baseline_file = git_dir / 'lock-solo-baseline.yaml'
generated_file = git_dir / 'lock-solo-generado.yaml'

if mode == '--antes':
    committed = git('show', 'HEAD:pnpm-lock.yaml')
    if LOCK.read_bytes() != committed or git('diff', '--cached', '--name-only', '--', str(LOCK)).strip():
        fail('pnpm-lock.yaml has changes of its own: commit or set them aside before pnpm add')
    baseline_file.write_bytes(committed)
    print(f'baseline saved ({len(committed)} bytes); now run pnpm add')
    sys.exit(0)

if not baseline_file.is_file():
    fail('No baseline: run lock-solo.py --antes <packages> on a clean lock before pnpm add')
generated = LOCK.read_bytes()
old = baseline_file.read_bytes().decode().splitlines(True)
new = generated.decode().splitlines(True)
out, reverted = [], 0
for op, a, b, c, d in difflib.SequenceMatcher(None, old, new, autojunk=False).get_opcodes():
    block = new[c:d]
    if op == 'replace' and (b - a) == (d - c) and not any(p in line for p in packages for line in block):
        out += old[a:b]
        reverted += b - a
    else:
        out += block
reduced = ''.join(out).encode()

if mode is None:
    sys.stdout.writelines(difflib.unified_diff(old, out, 'baseline/pnpm-lock.yaml', 'proposal/pnpm-lock.yaml'))
    print(f'proposal: {reverted} unrelated lines would go back to the baseline; nothing written (use --write)')
    sys.exit(0)

generated_file.write_bytes(generated)
LOCK.write_bytes(reduced)
try:
    code = subprocess.run(['pnpm', 'install', '--offline', '--frozen-lockfile'], stdin=subprocess.DEVNULL).returncode
except OSError as error:  # pnpm missing or not executable: same restore path as a failed install
    code = f'pnpm did not start: {error.strerror}'
if code != 0:
    if LOCK.read_bytes() == reduced:
        LOCK.write_bytes(generated)
        fail(f'frozen install failed ({code}): pnpm-lock.yaml is back to the bytes pnpm add generated')
    fail(f'frozen install failed ({code}) and pnpm-lock.yaml changed meanwhile: left as is; '
         f'the generated bytes are in {generated_file}')
baseline_file.unlink()
generated_file.unlink()
print(f'written: {reverted} unrelated lines back to the baseline; frozen install passed')

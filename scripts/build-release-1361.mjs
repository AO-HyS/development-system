// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { directiveTestInstructions, findTestDirectives } from "../src/test-change-policy.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// 1.36.1 narrows the check-no-tests document scan that 1.36.0 introduced: product documents are
// checked only for test commands and requests to write, keep or run tests, and installed skill trees
// are skipped. The release gardener keeps the strict list. Only the contract text changes; catalog
// 0.54.0 and every other artifact are reused.
const version = "1.36.1", previous = "1.36.0", catalogVersion = "0.54.0";
const prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some(arg => !["--write", "--check"].includes(arg)) || (write && process.argv.includes("--check"))) {
  throw new Error("Use --write or --check");
}
const generated = [`manifests/${version}.json`, `${prefix}/contract.md`];
if (write) for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
  for (const path of generated) {
    try {
      execFileSync("git", ["cat-file", "-e", `${ref}:${path}`], { cwd: root, stdio: "ignore" });
      throw new Error(`Published ${path} is immutable; create a new version`);
    } catch (error) {
      if (error instanceof Error && error.message.startsWith("Published")) throw error;
    }
  }
}
/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  if (!target.startsWith(`${root}/`)) throw new Error(`Release output escapes root: ${path}`);
  if (write) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data, { mode: 0o644 });
  } else if (!(await bytes(path)).equals(Buffer.from(data))) {
    throw new Error(`Generated bytes drift: ${path}`);
  }
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {boolean} condition @param {string} message */
function assert(condition, message) {
  if (!condition) throw new Error(`Release ${version} source check failed: ${message}`);
}

// The product-document scan reports directives and ignores descriptions; the gardener stays strict.
for (const line of [
  "Run `pnpm test` before you push.",
  "Write a regression test for the fix.",
  "Preserve tests for unknown hosts.",
]) assert(findTestDirectives(line).length === 1, `document scan misses a directive: ${line}`);
for (const line of [
  "The rule for this project: aohys has no automated tests. Do not create, run, or keep unit, integration, E2E, or browser tests.",
  "## Current Test Surface",
  "2. Prefer objective, testable rules over aesthetic preference.",
  "form validation and test locality live in",
  "do not write a regression test",
]) assert(findTestDirectives(line).length === 0, `document scan reports a description: ${line}`);
assert(findTestDirectives("Prefer testable rules.", directiveTestInstructions).length === 1, "gardener list lost the strict mention patterns");

const contractSource = (await bytes(`artifacts/${previous}/contract.md`)).toString();
const header = `# Development contract ${previous}`;
assert(contractSource.startsWith(`${header}\n`), "previous contract header");
const contract = contractSource.replace(header, `# Development contract ${version}`).trimEnd()
  + `\n\n## ${version}: check-no-tests reads directives, not mentions\n\n\`development-system check-no-tests\` reports a product document line only when it gives a test command or asks to write, keep or run tests. Descriptions such as tool names, "testable", "test surface" or coverage are no longer findings, and installed skill trees (\`.agents/skills\`, \`.claude/skills\` and similar) are skipped because the release gardener governs their catalog and upstream content. Historical records a repository keeps can be listed in \`config/no-tests-allow.json\`. The release gardener still applies the strict list to every installed instruction.\n`;
await output(`${prefix}/contract.md`, contract);

const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
const priorManifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
manifest.contractVersion = version;
let updatedCount = 0;
for (const artifact of manifest.artifacts) {
  if (artifact.logicalName === "development-contract") {
    artifact.sourcePath = `${prefix}/contract.md`;
    artifact.sha256 = hash(await bytes(artifact.sourcePath));
    updatedCount += 1;
  } else {
    if (artifact.sha256 !== hash(await bytes(artifact.sourcePath))) throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
    const prior = priorManifest.artifacts.find((/** @type {{id:string}} */ item) => item.id === artifact.id);
    if (!prior || JSON.stringify(artifact) !== JSON.stringify(prior)) throw new Error(`Unrelated manifest entry changed: ${artifact.id}`);
  }
}
assert(updatedCount >= 1, "previous manifest has no development-contract artifact");
const skillCatalog = manifest.artifacts.find((/** @type {{logicalName:string}} */ artifact) => artifact.logicalName === "skill-catalog");
assert(skillCatalog?.sourcePath === `catalog/${catalogVersion}.json`, `patch release must reuse catalog ${catalogVersion}`);
await outputJson(`manifests/${version}.json`, manifest);

const pkg = JSON.parse((await bytes("package.json")).toString());
if (pkg.version !== version || pkg.contractVersion !== version
  || pkg.scripts["release:prepare"] !== "node ./scripts/build-release-1361.mjs --check"
  || !pkg.scripts["skills:audit"].includes(`--version ${catalogVersion}`)
  || !pkg.scripts["skills:sync"].includes(`--version ${catalogVersion}`)) {
  throw new Error(`package.json release metadata does not match ${version} / catalog ${catalogVersion}`);
}
console.log(JSON.stringify({ version, previous, catalogVersion, artifacts: manifest.artifacts.length, operation: write ? "write" : "check" }));

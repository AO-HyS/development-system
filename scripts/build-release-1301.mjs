// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.30.1", previous = "1.30.0", catalogVersion = "0.49.0";
const prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some(arg => !["--write", "--check"].includes(arg)) || (write && process.argv.includes("--check"))) {
  throw new Error("Use --write or --check");
}
const generated = [
  `manifests/${version}.json`,
  `${prefix}/contract.md`,
  `${prefix}/runtime/headroom/cli.mjs`,
  `${prefix}/headroom-runtime-provenance.json`,
];
if (write) for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
  for (const path of generated) {
    try {
      execFileSync("git", ["cat-file", "-e", `${ref}:${path}`], { cwd: root, stdio: "ignore" });
      throw new Error(`Published ${path} is immutable; create a new version`);
    } catch (error) {
      if (error instanceof Error && error.message.startsWith("Published")) throw error;
    }
  }
}
/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  if (!target.startsWith(`${root}/`)) throw new Error(`Release output escapes root: ${path}`);
  if (write) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data);
  } else if (!(await bytes(path)).equals(Buffer.from(data))) {
    throw new Error(`Generated bytes drift: ${path}`);
  }
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");

const sourceRuntime = "runtime/headroom/cli.mjs";
const artifactRuntime = `${prefix}/runtime/headroom/cli.mjs`;
const contractSource = (await bytes(`artifacts/${previous}/contract.md`)).toString();
const contract = contractSource.replace("# Development contract 1.30.0", `# Development contract ${version}`)
  + `\n\n## T3 app-server launch correction\n\nPlace the Headroom provider overrides after the app-server subcommand. Codex applies command-line configuration in this position when T3 supplies its own -c settings. Ordinary exec argument ordering remains unchanged. This corrects launch configuration; transport coverage and provider usage still require observed evidence.\n`;
if (!contract.startsWith(contractSource.replace("# Development contract 1.30.0", `# Development contract ${version}`))) {
  throw new Error("Contract did not preserve the previous contract text");
}
await output(`${prefix}/contract.md`, contract);

const runtimeBytes = await bytes(sourceRuntime);
await output(artifactRuntime, runtimeBytes);
const provenance = JSON.parse((await bytes(`artifacts/${previous}/headroom-runtime-provenance.json`)).toString());
provenance.contractVersion = version;
provenance.correction = "T3 app-server provider overrides follow the subcommand; ordinary exec ordering is unchanged.";
const cliSource = provenance.sources.find((/** @type {{sourcePath:string}} */ source) => source.sourcePath === sourceRuntime);
if (!cliSource) throw new Error(`Missing Headroom source entry: ${sourceRuntime}`);
cliSource.artifactPath = artifactRuntime;
cliSource.sha256 = hash(runtimeBytes);
await outputJson(`${prefix}/headroom-runtime-provenance.json`, provenance);

const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
manifest.contractVersion = version;
/** @type {Map<string,string>} */
const updated = new Map([
  ["development-contract", `${prefix}/contract.md`],
  ["runtime--codex-development-system-runtime-headroom-cli-mjs", artifactRuntime],
  ["headroom-runtime-provenance", `${prefix}/headroom-runtime-provenance.json`],
]);
const updatedNames = new Set(updated.keys());
for (const artifact of manifest.artifacts) {
  const replacement = updated.get(artifact.logicalName);
  if (replacement) {
    artifact.sourcePath = replacement;
    artifact.sha256 = hash(await bytes(replacement));
  } else if (artifact.sha256 !== hash(await bytes(artifact.sourcePath))) {
    throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
  }
}
if (manifest.artifacts.filter((/** @type {{logicalName:string}} */ artifact) => updatedNames.has(artifact.logicalName)).length !== updated.size) {
  throw new Error("Previous manifest is missing a targeted patch artifact");
}
const priorManifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of manifest.artifacts) {
  if (!updatedNames.has(artifact.logicalName)) {
    const prior = priorManifest.artifacts.find((/** @type {{logicalName:string}} */ item) => item.logicalName === artifact.logicalName);
    if (!prior || JSON.stringify(artifact) !== JSON.stringify(prior)) throw new Error(`Unrelated manifest entry changed: ${artifact.logicalName}`);
  }
}
const skillCatalog = manifest.artifacts.find((/** @type {{logicalName:string}} */ artifact) => artifact.logicalName === "skill-catalog");
if (skillCatalog?.sourcePath !== `catalog/${catalogVersion}.json`) throw new Error("Patch release must reuse catalog 0.49.0");
await outputJson(`manifests/${version}.json`, manifest);

const pkg = JSON.parse((await bytes("package.json")).toString());
if (pkg.version !== version || pkg.contractVersion !== version
  || pkg.scripts["release:prepare"] !== `node ./scripts/build-release-1301.mjs --check`
  || !pkg.scripts["skills:audit"].includes(`--version ${catalogVersion}`)
  || !pkg.scripts["skills:sync"].includes(`--version ${catalogVersion}`)) {
  throw new Error("package.json release metadata does not match 1.30.1 / catalog 0.49.0");
}
console.log(JSON.stringify({ version, previous, catalogVersion, artifacts: manifest.artifacts.length, operation: write ? "write" : "check" }));

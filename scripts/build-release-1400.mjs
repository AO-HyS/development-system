// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSkillCatalog } from "../src/skills.mjs";
import { directiveTestInstructions, findTestDirectives, TEST_FILE_PATTERNS } from "../src/test-change-policy.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.40.0", previous = "1.39.0", catalogVersion = "0.58.0";
const prefix = `artifacts/${version}`;
const args = process.argv.slice(2);
if (args.length !== 1 || !["--write", "--check"].includes(args[0])) throw new Error("Use --write or --check");
const write = args[0] === "--write";
/** @param {string} file */
const bytes = file => readFile(resolve(root, file));
/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {boolean} condition @param {string} message */
function requireValid(condition, message) { if (!condition) throw new Error(`Release ${version}: ${message}`); }
/** @param {string} file @param {string|Buffer} data */
async function output(file, data) {
  requireValid(resolve(root, file).startsWith(`${root}/`), `output escapes root: ${file}`);
  if (write) {
    for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
      try { execFileSync("git", ["cat-file", "-e", `${ref}:${file}`], { cwd: root, stdio: "ignore" }); }
      catch { continue; }
      throw new Error(`Published ${file} is immutable; create a new version`);
    }
    await mkdir(dirname(resolve(root, file)), { recursive: true });
    await writeFile(resolve(root, file), data, { mode: 0o644 });
  } else requireValid((await bytes(file)).equals(Buffer.from(data)), `generated bytes drift: ${file}`);
}
/** @param {string} file @param {unknown} value */
const outputJson = (file, value) => output(file, JSON.stringify(value, null, 2) + "\n");
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const result = [];
  for (const entry of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const file = `${directory}/${entry.name}`;
    requireValid(![".DS_Store", "__pycache__", "node_modules", "evals"].includes(entry.name) && !entry.name.endsWith(".pyc"), `local residue: ${file}`);
    if (entry.isDirectory()) result.push(...await files(file));
    else { requireValid(entry.isFile(), `nonregular source: ${file}`); result.push(file); }
  }
  return result.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const file of await files(directory)) digest.update(relative(directory, file)).update("\0").update(await bytes(file)).update("\0");
  return digest.digest("hex");
}

const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of manifest.artifacts) requireValid(artifact.sha256 === hash(await bytes(artifact.sourcePath)), `previous input drift: ${artifact.sourcePath}`);
manifest.contractVersion = version;
const catalog = JSON.parse((await bytes("catalog/0.57.0.json")).toString());
requireValid((await validateSkillCatalog(catalog, root)).length === 0, "previous catalog drift");
catalog.catalogVersion = catalogVersion;

// The two changed skill trees are owned by their implementation writers. Never
// recopy older skill bytes over them; validate old inputs first, then hash every
// file in each new tree, retaining variant destinations and mirror relationships.
for (const name of ["working-backwards", "grill-with-docs"]) {
  const skill = catalog.skills.find((/** @type {any} */ row) => row.logicalName === name);
  requireValid(Boolean(skill), `missing skill: ${name}`);
  const destination = `${prefix}/skills/internal/${name}`;
  const folderSha256 = await folderHash(destination);
  skill.source = { ...skill.source, commit: "$INSTALL_COMMIT", path: destination };
  for (const variant of skill.variants) { variant.sourceDirectory = destination; variant.folderSha256 = folderSha256; }
}
for (const name of ["report140.css", "report-notebook.js"]) {
  requireValid((await bytes(`${prefix}/skills/internal/working-backwards/assets/${name}`))
    .equals(await bytes(`${prefix}/skills/internal/grill-with-docs/assets/reader/${name}`)), `shared presentation drift: ${name}`);
}
await outputJson(`catalog/${catalogVersion}.json`, catalog);

for (const artifact of manifest.artifacts) {
  if (artifact.logicalName === "personal-codex-instructions") {
    const destination = `${prefix}/global-codex-instructions.md`;
    const originalInstructions = (await bytes(artifact.sourcePath)).toString();
    const instructions = originalInstructions
      .replace("time, evidence, material gaps), keeping its field-notebook presentation, margin\nquestions, browser drafts and revisioned batch submission; Markdown is",
        "time, evidence, material gaps), using the approved AO HyS r5/p2 presentation\nshared with questionnaires, contextual questions, browser drafts and revisioned\nbatch submission; Markdown is");
    requireValid(instructions.includes("approved AO HyS r5/p2 presentation") && !instructions.includes("keeping its field-notebook"), "new report instruction missing");
    const fallbackStart = "## Authorized Claude Code account recovery (1.39.0)";
    requireValid(instructions.split(fallbackStart).length === 2 && instructions.slice(instructions.indexOf(fallbackStart)) === originalInstructions.slice(originalInstructions.indexOf(fallbackStart)), "account recovery guidance changed");
    await output(destination, instructions);
    artifact.sourcePath = destination;
  }
  if (artifact.logicalName === "development-contract") {
    const contract = (await bytes(artifact.sourcePath)).toString()
      .replace(`# Development contract ${previous}`, `# Development contract ${version}`)
      .replace("The paired skill catalog is 0.57.0.", `The paired skill catalog is ${catalogVersion}.`)
      .replace("elapsed time, evidence and material gaps. Preserve the field-notebook presentation,\nmargin questions, browser drafts and revisioned batch submission. Markdown is",
        "elapsed time, evidence and material gaps. Use the approved AO HyS r5/p2 presentation\nshared with questionnaires, contextual questions, browser drafts and revisioned batch submission. Markdown is")
      .replace("The field-notebook reader and margin questions from source fb6b5dd968281cd1a5c5563b940047102982a2fa are retained, with integration corrections documented separately.",
        "Contract 1.40.0 supersedes the field-notebook report presentation with the approved AO HyS r5/p2 shared report and questionnaire template (docs/design/report-template-brief.md). Reports lead with a summarized result and visible next steps; reports and questionnaires share warm AO HyS light/dark palettes, a visible persistent theme control and contextual questions. Composers close without sending, retain nonempty drafts and support deletion. Enviar saves a revisioned batch when served and also copies it, reporting save and clipboard outcomes separately. Existing question schemas, storage and same-origin security boundaries remain.");
    artifact.sourcePath = `${prefix}/contract.md`;
    await output(artifact.sourcePath, contract);
  }
  if (artifact.logicalName === "skill-catalog") artifact.sourcePath = `catalog/${catalogVersion}.json`;
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
// Inherit 1.39 account recovery and its codex-accounts artifact verbatim. This
// release neither appends fallback guidance again nor duplicates runtime rows.
requireValid(manifest.artifacts.filter((/** @type {any} */ artifact) => artifact.logicalName === "claude-orchestration-codex-accounts-mjs").length === 1, "account runtime must remain unique");
requireValid((await validateSkillCatalog(catalog, root)).length === 0, "new catalog invalid");
for (const file of await files(prefix)) {
  requireValid(!TEST_FILE_PATTERNS.some(pattern => pattern.test(file)), `automated test file: ${file}`);
  const text = (await bytes(file)).toString();
  requireValid(!/^(?:<{7}|={7}|>{7})/m.test(text), `conflict marker: ${file}`);
  if (/\.(md|toml|ya?ml)$/.test(file)) requireValid(findTestDirectives(text, directiveTestInstructions).length === 0, `automated test instruction: ${file}`);
}
const policy = JSON.parse((await bytes("claude/orchestration/policy.json")).toString());
requireValid(policy.review.engine === "codex" && policy.review.model === "gpt-6.1-sol" && policy.review.effort === "high", "review profile changed");
const pkg = JSON.parse((await bytes("package.json")).toString());
requireValid(pkg.version === version && pkg.contractVersion === version && pkg.scripts["release:prepare"] === "node ./scripts/build-release-1400.mjs --check", "package pins mismatch");
const guard = (await bytes("src/guardrails.mjs")).toString();
requireValid(guard.includes(`const guardCatalogVersion = "${catalogVersion}"`) && guard.includes(`const guardSetupVersion = "${version}"`), "guard pins mismatch");
await outputJson(`manifests/${version}.json`, manifest);
console.log(JSON.stringify({ version, previous, catalogVersion, artifacts: manifest.artifacts.length, operation: write ? "write" : "check", deploymentRequired: false }));

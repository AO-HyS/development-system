// @ts-check
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSkillCatalog } from '../src/skills.mjs';
import { checkRolePolicyOutputs, renderHostInstructions } from '../src/role-policy.mjs';
import { checkActiveToolingDocs } from './check-active-tooling-docs.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = '2.1.2', previous = '2.1.1', catalogVersion = '0.61.0', prefix = `artifacts/${version}`;
const mode = process.argv[2];
if (process.argv.length !== 3 || !['--write', '--check'].includes(mode)) throw new Error('Use --write or --check');
const write = mode === '--write';
/** @param {string|Buffer} value */
const hash = value => createHash('sha256').update(value).digest('hex');
/** @param {string} file */
const bytes = file => readFile(resolve(root, file));
/** @param {string} file @param {string|Buffer} value */
async function output(file, value) {
  if (!write) { if (!(await bytes(file)).equals(Buffer.from(value))) throw new Error(`Generated bytes drift: ${file}`); return; }
  for (const ref of ['refs/remotes/origin/main', `refs/tags/v${version}`]) {
    try { execFileSync('git', ['cat-file', '-e', `${ref}:${file}`], { cwd: root, stdio: 'ignore' }); } catch { continue; }
    throw new Error(`Published ${file} is immutable; create a new version`);
  }
  await mkdir(dirname(resolve(root, file)), { recursive: true });
  await writeFile(resolve(root, file), value);
}
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const found = [];
  for (const entry of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const file = `${directory}/${entry.name}`;
    if (entry.isDirectory()) found.push(...await files(file));
    else if (entry.isFile()) found.push(file);
    else throw new Error(`Nonregular skill source: ${file}`);
  }
  return found.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash('sha256');
  for (const file of await files(directory)) digest.update(relative(directory, file)).update('\0').update(await bytes(file)).update('\0');
  return digest.digest('hex');
}
const roleCheck = checkRolePolicyOutputs(root);
if (!roleCheck.valid) throw new Error(roleCheck.errors.join('; '));
const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of manifest.artifacts) if (hash(await bytes(artifact.sourcePath)) !== artifact.sha256) throw new Error(`Previous immutable artifact drift: ${artifact.sourcePath}`);
manifest.contractVersion = version;
const catalog = JSON.parse((await bytes(`catalog/${catalogVersion}.json`)).toString());
const skill = catalog.skills.find((/** @type {any} */ entry) => entry.logicalName === 'coding-orchestration');
if (!skill) throw new Error('Missing coding-orchestration skill');
for (const variant of skill.variants) variant.folderSha256 = await folderHash(variant.sourceDirectory);
await output(`catalog/${catalogVersion}.json`, JSON.stringify(catalog, null, 2) + '\n');
for (const artifact of manifest.artifacts) {
  const name = artifact.logicalName;
  let source = null;
  if (name.startsWith('claude-orchestration-')) source = `claude/orchestration/${artifact.sourcePath.split('/').at(-1)}`;
  else if (name.startsWith('claude-agent-')) source = `claude/agents/${artifact.sourcePath.split('/').at(-1)}`;
  else if (name === 'claude-rule-orchestration-md') source = 'claude/rules/orchestration.md';
  if (source) {
    const value = await bytes(source);
    if (!value.equals(await bytes(artifact.sourcePath))) {
      artifact.sourcePath = source.startsWith('claude/orchestration/') ? `${prefix}/runtime/claude-orchestration/${source.split('/').at(-1)}` : `${prefix}/${source}`;
      await output(artifact.sourcePath, value);
    }
  }
  if (name === 'agent-roster') {
    artifact.sourcePath = `config/${version}/agent-roster.json`;
    await output(artifact.sourcePath, await bytes('config/agent-roster.json'));
  }
  if (name === 'personal-codex-instructions') {
    const original = (await bytes(artifact.sourcePath)).toString();
    const start = original.indexOf('## Codex host'), end = original.indexOf('## Authorized Claude Code account recovery (1.39.0)');
    if (start < 0 || end <= start) throw new Error('Host/recovery boundaries missing');
    artifact.sourcePath = `${prefix}/global-codex-instructions.md`;
    await output(artifact.sourcePath, original.slice(0, start) + renderHostInstructions('codex') + '\n\n' + renderHostInstructions('claude') + '\n\n' + original.slice(end));
  }
  if (['development-contract', 'orchestration-contract', 'model-routing'].includes(name)) {
    const original = (await bytes(artifact.sourcePath)).toString();
    const hostStart = original.indexOf('\n## Generated host role profiles');
    const browserStart = original.indexOf('\n## Browser resource preparation');
    if (hostStart < 0) throw new Error(`Missing generated host guidance: ${name}`);
    const suffix = browserStart > hostStart ? original.slice(browserStart) : '';
    const title = name === 'development-contract' ? 'Development contract' : name === 'orchestration-contract' ? 'Orchestration contract' : 'Model routing';
    const current = original.slice(0, hostStart).replace(/^# [^\n]+/, `# ${title} ${version}`).replace(/\b0\.60\.0\b/g, catalogVersion);
    artifact.sourcePath = `${prefix}/${name === 'development-contract' ? 'contract.md' : name === 'orchestration-contract' ? 'orchestration-contract.md' : 'model-routing.md'}`;
    await output(artifact.sourcePath, current + '\n## Generated host role profiles\n\n' + renderHostInstructions('codex') + '\n\n' + renderHostInstructions('claude') + '\n' + suffix);
  }
  if (name === 'skill-catalog') artifact.sourcePath = `catalog/${catalogVersion}.json`;
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
await output(`manifests/${version}.json`, JSON.stringify(manifest, null, 2) + '\n');
const pkg = JSON.parse((await bytes('package.json')).toString());
const errors = await validateSkillCatalog(catalog, root);
if (errors.length || pkg.version !== version || pkg.contractVersion !== version) throw new Error(`Invalid release inputs: ${errors.join('; ')}`);
await checkActiveToolingDocs();
console.log(JSON.stringify({ version, previous, catalogVersion, artifacts: manifest.artifacts.length, operation: mode }));

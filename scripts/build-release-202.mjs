// @ts-check
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSkillCatalog } from '../src/skills.mjs';
import { checkRolePolicyOutputs } from '../src/role-policy.mjs';
import { checkActiveToolingDocs } from './check-active-tooling-docs.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = '2.0.2';
const args = process.argv.slice(2);
if (args.length !== 1 || !['--write', '--check'].includes(args[0])) throw new Error('Use --write or --check');
const write = args[0] === '--write';
/** @param {string|Buffer} value */
const hash = value => createHash('sha256').update(value).digest('hex');
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string} value */
async function output(path, value) {
  if (!write) { if (!(await bytes(path)).equals(Buffer.from(value))) throw new Error(`Generated bytes drift: ${path}`); return; }
  for (const ref of ['refs/remotes/origin/main', `refs/tags/v${version}`]) {
    try { execFileSync('git', ['cat-file', '-e', `${ref}:${path}`], { cwd: root, stdio: 'ignore' }); }
    catch { continue; }
    throw new Error(`Published ${path} is immutable; create a new version`);
  }
  await mkdir(dirname(resolve(root, path)), { recursive: true });
  await writeFile(resolve(root, path), value);
}
const manifest = JSON.parse((await bytes('manifests/2.0.1.json')).toString());
for (const artifact of manifest.artifacts) if (hash(await bytes(artifact.sourcePath)) !== artifact.sha256) throw new Error(`Previous immutable artifact drift: ${artifact.sourcePath}`);
manifest.contractVersion = version;
const contract = manifest.artifacts.find((/** @type {any} */ a) => a.logicalName === 'development-contract');
if (!contract) throw new Error('Previous manifest lacks development contract');
const text = (await bytes(contract.sourcePath)).toString().replace(/^# Development contract 2\.0\.1/m, '# Development contract 2.0.2')
  + '\n## Active agent instruction coverage\n\nThe no-tests CLI also scans configured GitHub and native agent instruction Markdown. This is bounded directive detection, not exhaustive natural-language enforcement or proof of native hook prevention. Retire foreign instructions by source evidence; a successful scanner result does not prove product relevance or host loading.\n';
contract.sourcePath = 'artifacts/2.0.2/contract.md';
contract.sha256 = hash(text);
await output(contract.sourcePath, text);
await output(`manifests/${version}.json`, JSON.stringify(manifest, null, 2) + '\n');
const catalog = JSON.parse((await bytes('catalog/0.60.0.json')).toString());
const errors = await validateSkillCatalog(catalog, root);
const roles = await checkRolePolicyOutputs(root);
const pkg = JSON.parse((await bytes('package.json')).toString());
if (errors.length || !roles.valid || pkg.version !== version || pkg.contractVersion !== version) throw new Error(`Release inputs invalid: ${[...errors, ...roles.errors].join('; ')}`);
await checkActiveToolingDocs();
console.log(JSON.stringify({ version, previous: '2.0.1', catalogVersion: '0.60.0', artifacts: manifest.artifacts.length, operation: write ? 'write' : 'check' }));

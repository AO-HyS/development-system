// @ts-check
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSkillCatalog } from '../src/skills.mjs';
import { checkRolePolicyOutputs } from '../src/role-policy.mjs';
import { checkActiveToolingDocs } from './check-active-tooling-docs.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const version='2.1.1', prefix=`artifacts/${version}`;
const mode=process.argv[2];
if(process.argv.length!==3||!['--write','--check'].includes(mode)) throw new Error('Use --write or --check');
const write=mode==='--write';
/** @param {string|Buffer} value */
const hash=value=>createHash('sha256').update(value).digest('hex');
/** @param {string} file */
const bytes=file=>readFile(resolve(root,file));
/** @param {string} file @param {string|Buffer} value */
async function output(file,value) {
  if(!write) {if(!(await bytes(file)).equals(Buffer.from(value))) throw new Error(`Generated bytes drift: ${file}`);return;}
  for(const ref of ['refs/remotes/origin/main',`refs/tags/v${version}`]) {
    try {execFileSync('git',['cat-file','-e',`${ref}:${file}`],{cwd:root,stdio:'ignore'});} catch {continue;}
    throw new Error(`Published ${file} is immutable; create a new version`);
  }
  await mkdir(dirname(resolve(root,file)),{recursive:true}); await writeFile(resolve(root,file),value);
}
const manifest=JSON.parse((await bytes('manifests/2.1.0.json')).toString());
for(const artifact of manifest.artifacts) if(hash(await bytes(artifact.sourcePath))!==artifact.sha256) throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
manifest.contractVersion=version;
for(const name of ['development-contract','personal-codex-instructions']) {
  const artifact=manifest.artifacts.find((/** @type {any} */ a)=>a.logicalName===name);
  if(!artifact) throw new Error(`Missing ${name}`);
  let value=(await bytes(artifact.sourcePath)).toString();
  if(name==='development-contract') value=value.replace(/^# Development contract 2\.1\.0/m,`# Development contract ${version}`);
  artifact.sourcePath=`${prefix}/${name==='development-contract'?'contract.md':'global-codex-instructions.md'}`;
  artifact.sha256=hash(value); await output(artifact.sourcePath,value);
}
for(const name of ['codex-review.mjs','roster-guard.mjs']) {
  const artifact=manifest.artifacts.find((/** @type {any} */ a)=>a.logicalName===`claude-orchestration-${name.replace('.','-')}`);
  if(!artifact) throw new Error(`Missing managed ${name}`);
  const value=await bytes(`claude/orchestration/${name}`);
  artifact.sourcePath=`${prefix}/runtime/claude-orchestration/${name}`;
  artifact.sha256=hash(value); await output(artifact.sourcePath,value);
}
for(const name of ['pool.mjs','cli.mjs']) {
  const value=await bytes(`runtime/native-browser/${name}`), sourcePath=`${prefix}/runtime/native-browser/${name}`;
  await output(sourcePath,value);
  const id=`native-browser-${name.replace('.','-')}`;
  const artifact=manifest.artifacts.find((/** @type {any} */ a)=>a.logicalName===id);
  if(!artifact) throw new Error(`Missing managed ${id}`);
  artifact.sourcePath=sourcePath; artifact.sha256=hash(value);
}
await output(`manifests/${version}.json`,JSON.stringify(manifest,null,2)+'\n');
const pkg=JSON.parse((await bytes('package.json')).toString());
const catalog=JSON.parse((await bytes('catalog/0.60.0.json')).toString());
const errors=await validateSkillCatalog(catalog,root), roles=await checkRolePolicyOutputs(root);
if(errors.length||!roles.valid||pkg.version!==version||pkg.contractVersion!==version) throw new Error(`Release inputs invalid: ${[...errors,...roles.errors].join('; ')}`);
await checkActiveToolingDocs();
console.log(JSON.stringify({version,previous:'2.1.0',catalogVersion:'0.60.0',artifacts:manifest.artifacts.length,operation:mode}));

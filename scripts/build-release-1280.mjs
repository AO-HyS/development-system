import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSkillCatalog } from "../src/skills.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.28.0", catalogVersion = "0.47.0", prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some(arg => !["--write", "--check"].includes(arg)) || write && process.argv.includes("--check")) throw new Error("Use --write or --check");
if (write) {
  for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
    for (const path of [`manifests/${version}.json`, `catalog/${catalogVersion}.json`]) {
      let published = false;
      try { execFileSync("git", ["cat-file", "-e", `${ref}:${path}`], { cwd: root, stdio: "ignore" }); published = true; } catch {}
      if (published) throw new Error(`Published ${path} is immutable; create a new version`);
    }
  }
}
/** @param {string|Buffer} bytes */
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  if (write) { await mkdir(dirname(resolve(root, path)), { recursive: true }); await writeFile(resolve(root, path), data); }
  else if (!(await bytes(path)).equals(Buffer.from(data))) throw new Error(`Generated bytes drift: ${path}`);
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {string} directory */
async function files(directory) {
  /** @type {string[]} */ const result = [];
  /** @param {string} path */
  async function walk(path) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const full = resolve(path, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) result.push(full);
      else throw new Error(`Nonregular release source: ${full}`);
    }
  }
  await walk(resolve(root, directory));
  return result.sort();
}
/** Canonical helper retained from build-release-1260; validateSkillCatalog independently checks it.
 * @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const file of await files(directory)) digest.update(relative(resolve(root, directory), file)).update("\0").update(await readFile(file)).update("\0");
  return digest.digest("hex");
}

// The notebook report presentation is authored directly as the new immutable
// artifact version; this builder proves the delta against 1.26.0 instead of
// regenerating whole-file rewrites.
const previousSkill = "artifacts/1.26.0/skills/internal/working-backwards";
const skillDirectory = `${prefix}/skills/internal/working-backwards`;
const previousFiles = (await files(previousSkill)).map(path => relative(resolve(root, previousSkill), path));
const currentFiles = (await files(skillDirectory)).map(path => relative(resolve(root, skillDirectory), path));
const added = ["assets/bricolage-grotesque-latin.woff2", "assets/licenses/bricolage-OFL.txt", "assets/report-notebook.js"];
const changed = ["assets/report-evidence.css", "assets/visual-document.css", "scripts/reader-live.mjs", "scripts/report-evidence.mjs", "scripts/t3-reader.mjs", "scripts/visual-document.mjs"];
if (JSON.stringify(currentFiles) !== JSON.stringify([...previousFiles, ...added].sort())) throw new Error("The 1.28.0 skill inventory differs from 1.26.0 plus the notebook assets");
for (const path of previousFiles) {
  const before = await readFile(resolve(root, previousSkill, path));
  const after = await readFile(resolve(root, skillDirectory, path));
  if (changed.includes(path) ? before.equals(after) : !before.equals(after)) throw new Error(`Unexpected byte relationship: ${path}`);
}
const license = (await bytes(`${skillDirectory}/assets/licenses/bricolage-OFL.txt`)).toString();
if (!license.includes("SIL OPEN FONT LICENSE") || !license.includes("Bricolage Grotesque")) throw new Error("The Bricolage license text is missing");

const catalog = JSON.parse((await bytes("catalog/0.46.1.json")).toString());
catalog.catalogVersion = catalogVersion;
const skill = catalog.skills.find((/** @type {any} */ entry) => entry.logicalName === "working-backwards");
if (!skill || skill.variants.length !== 1) throw new Error("Published working-backwards inventory changed");
skill.source.path = skillDirectory;
const skillHash = await folderHash(skillDirectory);
for (const variant of skill.variants) { variant.sourceDirectory = skillDirectory; variant.folderSha256 = skillHash; }
const variants = catalog.skills.reduce((/** @type {number} */ count, /** @type {any} */ entry) => count + entry.variants.length, 0);
if (catalog.skills.length !== 104 || variants !== 140 || catalog.maxCatalogEntries !== 512) throw new Error("Published catalog inventory changed");
const catalogErrors = await validateSkillCatalog(catalog, root);
if (catalogErrors.length) throw new Error(catalogErrors.join("\n"));
await outputJson(`catalog/${catalogVersion}.json`, catalog);

const contract = (await bytes("artifacts/1.27.1/contract.md")).toString() + "\n## Field-notebook reports and margin questions (1.28.0)\n\nStandalone technical reports render as a field-notebook page: a stamped label, the verdict at display scale, a status row, numbered findings with verification marks, a numbered contents index and a margin column. The reader model accepts optional `verdict`, `reference`, `signals` (tone, label, text) and `findings` (title, detail, verification status); content still comes from the canonical Markdown. Every prior capability remains: evidence comparisons and recordings, PR Lens maps, charts, tables, code, themes, print and the source footer. Paragraphs, findings, tables and charts carry stable anchors; clicking one opens a margin question composer. Drafts persist in the browser, and a batch can be submitted to the bounded local Reader server, which stores each submission as a revisioned receipt beside the report under `.questions/` and refuses cross-origin, conflicting or unsafe writes. Reports opened from a file keep the copy and download fallback. The single-file report remains offline: fonts embed as data, executable code stays bound to its CSP hash, and network access is limited to the same origin that served the page. Question submission never grants implementation or release authority.\n";

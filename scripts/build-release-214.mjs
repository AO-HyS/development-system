// @ts-check
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSkillCatalog } from '../src/skills.mjs';
import { checkActiveToolingDocs } from './check-active-tooling-docs.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = '2.1.4', previous = '2.1.3', catalogVersion = '0.64.0';
const names = ['correct', 'architect', 'benchmark-checklist'];
const upstreamCommit = '9d76bcab133aefcccb16121d7be874e6aa823729';
const mode = process.argv[2];
if (process.argv.length !== 3 || !['--write', '--check'].includes(mode)) throw new Error('Use --write or --check');
/** @param {string|Buffer} value */
const hash = value => createHash('sha256').update(value).digest('hex');
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} value */
async function output(path, value) {
  if (mode === '--check') {
    if (!(await bytes(path)).equals(Buffer.from(value))) throw new Error(`Generated bytes drift: ${path}`);
    return;
  }
  for (const ref of ['refs/remotes/origin/main', `refs/tags/v${version}`]) {
    try { execFileSync('git', ['cat-file', '-e', `${ref}:${path}`], { cwd: root, stdio: 'ignore' }); } catch { continue; }
    throw new Error(`Published ${path} is immutable; create a new version`);
  }
  await mkdir(dirname(resolve(root, path)), { recursive: true });
  await writeFile(resolve(root, path), value);
}
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const result = [];
  for (const entry of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await files(path));
    else if (entry.isFile()) result.push(path);
    else throw new Error(`Nonregular skill source: ${path}`);
  }
  return result.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash('sha256');
  for (const path of await files(directory)) digest.update(relative(directory, path)).update('\0').update(await bytes(path)).update('\0');
  return digest.digest('hex');
}

const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of manifest.artifacts) {
  if (hash(await bytes(artifact.sourcePath)) !== artifact.sha256) throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
}
const catalog = JSON.parse((await bytes('catalog/0.62.0.json')).toString());
catalog.catalogVersion = catalogVersion;
for (const name of names) {
  if (catalog.skills.some((/** @type {{logicalName:string}} */ row) => row.logicalName === name)) throw new Error(`Skill already exists: ${name}`);
  const directory = `artifacts/${version}/skills/external/${name}`;
  const provenance = JSON.parse((await bytes(`${directory}/upstream.json`)).toString());
  if (provenance.commit !== upstreamCommit || provenance.path !== `pstack/skills/${name}`) throw new Error(`Unexpected upstream: ${name}`);
  const digest = await folderHash(directory);
  catalog.skills.push({
    logicalName: name,
    physicalHarnesses: ['codex', 'claude'],
    source: {
      repository: 'https://github.com/AO-HyS/development-system', commit: '$INSTALL_COMMIT', path: directory,
      upstreamReference: { repository: 'https://github.com/cursor/plugins', license: 'MIT', commit: upstreamCommit,
        path: provenance.path, capabilityTreeSha256: provenance.capabilityTreeSha256 },
    },
    variants: [
      { id: `${name}.codex`, harness: 'codex', sourceDirectory: directory, destination: `.agents/skills/${name}`, folderSha256: digest, expectedMirrorOf: null },
      { id: `${name}.claude`, harness: 'claude', sourceDirectory: directory, destination: `.claude/skills/${name}`, folderSha256: digest, expectedMirrorOf: `${name}.codex`, install: 'symlink' },
    ],
  });
}
const errors = await validateSkillCatalog(catalog, root);
if (errors.length) throw new Error(errors.join('; '));
await output(`catalog/${catalogVersion}.json`, JSON.stringify(catalog, null, 2) + '\n');
manifest.contractVersion = version;
for (const artifact of manifest.artifacts) {
  if (artifact.logicalName === 'skill-catalog') artifact.sourcePath = `catalog/${catalogVersion}.json`;
  if (['development-contract', 'orchestration-contract', 'model-routing'].includes(artifact.logicalName)) {
    const content = (await bytes(artifact.sourcePath)).toString().replaceAll(previous, version).replaceAll('0.62.0', catalogVersion);
    const filename = artifact.logicalName === 'development-contract' ? 'contract' : artifact.logicalName;
    artifact.sourcePath = `artifacts/${version}/${filename}.md`;
    await output(artifact.sourcePath, content);
  }
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
await output(`manifests/${version}.json`, JSON.stringify(manifest, null, 2) + '\n');
const pkg = JSON.parse((await bytes('package.json')).toString());
if (pkg.version !== version || pkg.contractVersion !== version) throw new Error('Package version mismatch');
await checkActiveToolingDocs();
console.log(JSON.stringify({ version, previous, catalogVersion, addedSkills: names, operation: mode }));

// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// 1.34.0 ships no skill changes: the paired catalog stays 0.51.0 and is not regenerated.
const version = "1.34.0", previous = "1.33.0", catalogVersion = "0.51.0";
const prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some(arg => !["--write", "--check"].includes(arg)) || (write && process.argv.includes("--check"))) {
  throw new Error("Use --write or --check");
}
if (write) for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
  for (const path of [`manifests/${version}.json`, `${prefix}/contract.md`]) {
    try {
      execFileSync("git", ["cat-file", "-e", `${ref}:${path}`], { cwd: root, stdio: "ignore" });
      throw new Error(`Published ${path} is immutable; create a new version`);
    } catch (error) {
      if (error instanceof Error && error.message.startsWith("Published")) throw error;
    }
  }
}
/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  if (!target.startsWith(`${root}/`)) throw new Error(`Release output escapes root: ${path}`);
  if (write) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data, { mode: 0o644 });
  } else if (!(await bytes(path)).equals(Buffer.from(data))) {
    throw new Error(`Generated bytes drift: ${path}`);
  }
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {string} text @param {string} from @param {string} to */
function replaceOnce(text, from, to) {
  if (text.split(from).length !== 2) throw new Error(`Expected one occurrence of: ${from.slice(0, 70)}`);
  return text.replace(from, to);
}
/** @param {boolean} condition @param {string} message */
function assert(condition, message) {
  if (!condition) throw new Error(`Release ${version} source check failed: ${message}`);
}
// Claude sources: byte-identical copies of the operator's Claude orchestration files.
const orchestrationFiles = ["roster-guard.mjs", "policy.json", "run-report.py", "codex-review.mjs"];
// codex-review.mjs is new in 1.34.0: it is added to the manifest; the others are repointed.
const addedOrchestration = ["codex-review.mjs"];
const agentNames = (await readdir(resolve(root, "claude/agents"), { withFileTypes: true }))
  .map(entry => {
    if (!entry.isFile() || !entry.name.endsWith(".md")) throw new Error(`Unexpected entry in claude/agents: ${entry.name}`);
    return entry.name.slice(0, -3);
  })
  .sort();
assert(agentNames.length === 17, `expected 17 agent files, found ${agentNames.length}`);

/** @type {Array<{logicalName: string, sourcePath: string, artifactPath: string, destination: string, added?: boolean}>} */
const items = [
  ...orchestrationFiles.map(file => ({
    logicalName: `claude-orchestration-${file.replace(/\./g, "-")}`,
    sourcePath: `claude/orchestration/${file}`,
    artifactPath: `${prefix}/runtime/claude-orchestration/${file}`,
    destination: `.codex/development-system/runtime/claude-orchestration/${file}`,
    added: addedOrchestration.includes(file),
  })),
  ...agentNames.map(name => ({
    logicalName: `claude-agent-${name.toLowerCase()}`,
    sourcePath: `claude/agents/${name}.md`,
    artifactPath: `${prefix}/claude/agents/${name}.md`,
    destination: `.claude/agents/${name}.md`,
  })),
  {
    logicalName: "claude-rule-orchestration-md",
    sourcePath: "claude/rules/orchestration.md",
    artifactPath: `${prefix}/claude/rules/orchestration.md`,
    destination: ".claude/rules/orchestration.md",
  },
];
assert(items.length === 22, `expected 22 sources, found ${items.length}`);
assert(new Set(items.map(item => item.logicalName)).size === items.length, "logical names are not unique");

/** @type {Map<string, Buffer>} */
const sources = new Map();
for (const item of items) {
  const data = await bytes(item.sourcePath);
  const text = data.toString();
  for (const forbidden of ["/Users/", "corrortiz"]) assert(!text.includes(forbidden), `${item.sourcePath} contains ${forbidden}`);
  // run-report.py keeps a Haiku price row and roster-guard.mjs maps legacy haiku memory rows and denies
  // model haiku, so only the agents, the rule and policy.json must be free of Haiku.
  if (!["claude/orchestration/run-report.py", "claude/orchestration/roster-guard.mjs"].includes(item.sourcePath)) assert(!/haiku/i.test(text), `${item.sourcePath} mentions Haiku`);
  sources.set(item.sourcePath, data);
}

const tiers = ["sonnet", "opus_low", "opus_medium", "opus_high", "fable"];
const policy = JSON.parse(/** @type {Buffer} */ (sources.get("claude/orchestration/policy.json")).toString());
assert(policy.version === "2026-09-26.1", `policy.version is ${policy.version}`);
assert(policy.fableMarker === "Fable scope:", `policy.fableMarker is ${policy.fableMarker}`);
const review = policy.review ?? {};
assert(review.engine === "codex" && review.model === "gpt-6-astra" && review.effort === "xhigh", "policy.review must be codex, gpt-6-astra, xhigh");
assert(review.maxParallel === 5 && review.roundsWithoutRationale === 3, "policy.review maxParallel 5 and roundsWithoutRationale 3");
assert(typeof review.stateDir === "string" && review.stateDir.startsWith("~/"), "policy.review.stateDir must start with ~/");
const retired = Object.entries(policy.roster).filter(([, role]) => role.retired === true).map(([name]) => name).sort();
assert(JSON.stringify(retired) === JSON.stringify(["plan-reviewer", "security-reviewer"]), `retired roles are ${retired.join(",")}`);
const rosterKeys = Object.keys(policy.roster ?? {}).sort();
assert(JSON.stringify(rosterKeys) === JSON.stringify(agentNames), `roster keys ${rosterKeys.join(",")} differ from agent files ${agentNames.join(",")}`);
for (const [name, role] of Object.entries(policy.roster)) {
  assert(typeof role.family === "string" && role.family.length > 0, `roster.${name} has no family`);
  assert(tiers.includes(role.tier), `roster.${name} tier ${role.tier} is not one of ${tiers.join(", ")}`);
}
assert(JSON.stringify(Object.keys(policy.tier?.question?.criteria ?? {})) === JSON.stringify(tiers), "policy.tier.question.criteria keys differ from the tier list");
for (const [label, value] of [["stateDir", policy.stateDir], ["jev.cli", policy.jev?.cli], ["tier.credentialFile", policy.tier?.credentialFile]]) {
  assert(typeof value === "string" && value.startsWith("~/"), `policy.${label} must start with ~/`);
}
/** @type {Record<string, string>} */
const effortByTier = { sonnet: "low", opus_low: "low", opus_medium: "medium", opus_high: "high", fable: "high" };
const sonnetRoles = ["Explore", "code-mapper", "docs-researcher", "mechanical-worker"];
for (const name of agentNames) {
  const text = /** @type {Buffer} */ (sources.get(`claude/agents/${name}.md`)).toString();
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  assert(match !== null, `claude/agents/${name}.md has no frontmatter`);
  /** @type {Record<string,string>} */ const front = {};
  // Only top-level keys: indented lines (such as a nested hooks: block) are skipped.
  for (const line of /** @type {RegExpExecArray} */ (match)[1].split("\n")) {
    const field = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (field) front[field[1]] = field[2].trim();
  }
  const role = policy.roster[name];
  assert(front.name === name, `claude/agents/${name}.md name is ${front.name}`);
  assert(front.model === role.model, `claude/agents/${name}.md model ${front.model} differs from roster ${role.model}`);
  assert(front.effort === effortByTier[role.tier], `claude/agents/${name}.md effort ${front.effort} does not match tier ${role.tier}`);
  if (sonnetRoles.includes(name)) {
    assert(front.model === "sonnet" && front.effort === "low" && role.tier === "sonnet", `claude/agents/${name}.md must be model sonnet, effort low, tier sonnet`);
  }
}

for (const item of items) await output(item.artifactPath, /** @type {Buffer} */ (sources.get(item.sourcePath)));

// Runtime: the Stop report gate shared by Claude Code and Codex.
const stopGate = {
  logicalName: "runtime--codex-development-system-runtime-report-gate-stop-gate-mjs",
  sourcePath: "runtime/report-gate/stop-gate.mjs",
  artifactPath: `${prefix}/runtime/report-gate/stop-gate.mjs`,
  destination: ".codex/development-system/runtime/report-gate/stop-gate.mjs",
};
// 1.34.0 updates the gate (a running codex-review defers it), so it is repointed.
const stopGateBytes = await bytes(stopGate.sourcePath);
assert(stopGateBytes.toString().includes("codex-review"), `${stopGate.sourcePath} does not defer to a pending codex-review`);
await output(stopGate.artifactPath, stopGateBytes);

const contractSource = (await bytes(`artifacts/${previous}/contract.md`)).toString();
const contractBase = replaceOnce(contractSource, `# Development contract ${previous}`, `# Development contract ${version}`);
const contract = `${contractBase.trimEnd()}\n\n## Astra reviews through codex-review\n\nContract ${version} moves plan, diff, security and visual reviews to Astra XHigh through \`codex-review.mjs\`, installed with the Claude orchestration runtime. It runs \`codex exec\` in a read-only sandbox on the review packet (images through \`--image\`), writes findings.md, the event stream and a receipt, and prints one JSON receipt line with the requested model and effort and the observed ones read from the Codex session log, or unknown. The coordinator launches it in the background and is woken when it exits, so it never polls or sleeps. From the fourth round of the same objective a \`Round rationale:\` line naming an open critical or high finding is required; otherwise remaining findings become documented gaps or next-version work. At most five reviews run at once, and the Stop report gate waits while one is running. A \`--computer-use\` mode runs one Codex Computer Use operator at a time through the same launcher, and browser-qa runs only as a declared fallback. The Fable reviewers plan-reviewer and security-reviewer are retired, and the Claude reviewers run only with a declared \`Codex fallback:\` line that the report states. A halted or failed subagent's packet is split into smaller packets and dispatched again rather than absorbed by the coordinator. Installed files do not prove that a harness runs these hooks or that they influenced a session; that needs observed-session evidence.\n`;
assert(contract.includes(`The paired skill catalog is ${catalogVersion}.`), "contract lost the paired catalog reference");
await output(`${prefix}/contract.md`, contract);

// Manifest: previous artifacts stay byte-identical unless replaced here.
const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
manifest.contractVersion = version;
/** @type {Map<string,string>} */
const updated = new Map([
  ["development-contract", `${prefix}/contract.md`],
  ...items.filter(item => !item.added).map(item => /** @type {[string,string]} */ ([item.logicalName, item.artifactPath])),
  [stopGate.logicalName, stopGate.artifactPath],
]);
const claudeDestinations = new Map(items.map(item => [item.logicalName, item.destination]));
for (const artifact of manifest.artifacts) {
  const replacement = updated.get(artifact.logicalName);
  if (claudeDestinations.has(artifact.logicalName)) {
    assert(artifact.destination === claudeDestinations.get(artifact.logicalName) && artifact.harness === "claude", `${artifact.logicalName} destination or harness changed`);
  }
  if (!replacement && artifact.sha256 !== hash(await bytes(artifact.sourcePath))) throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
  if (replacement) artifact.sourcePath = replacement;
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
if (manifest.artifacts.filter((/** @type {{logicalName:string}} */ artifact) => updated.has(artifact.logicalName)).length !== updated.size) {
  throw new Error("Previous manifest is missing a targeted artifact");
}
assert(manifest.artifacts.find((/** @type {{logicalName:string}} */ artifact) => artifact.logicalName === "skill-catalog")?.sourcePath === `catalog/${catalogVersion}.json`, `skill-catalog does not point at catalog/${catalogVersion}.json`);
const previousCount = manifest.artifacts.length;
const added = items.filter(item => item.added);
for (const item of added) {
  if (manifest.artifacts.some((/** @type {{logicalName:string}} */ artifact) => artifact.logicalName === item.logicalName)) {
    throw new Error(`Duplicate logical name: ${item.logicalName}`);
  }
  manifest.artifacts.push({
    id: item.logicalName,
    logicalName: item.logicalName,
    sourcePath: item.artifactPath,
    destination: item.destination,
    harness: "claude",
    sha256: hash(/** @type {Buffer} */ (sources.get(item.sourcePath))),
    expectedMirrorOf: null,
  });
}
await outputJson(`manifests/${version}.json`, manifest);

const pkg = JSON.parse((await bytes("package.json")).toString());
const scripts = pkg.scripts ?? {};
if (pkg.version !== version || pkg.contractVersion !== version
  || scripts["release:prepare"] !== `node ./scripts/build-release-1340.mjs --check`
  || !scripts["skills:audit"]?.includes(`--version ${catalogVersion}`)
  || !scripts["skills:sync"]?.includes(`--version ${catalogVersion}`)
  || scripts.verify !== "pnpm run roster:check && pnpm run typecheck && pnpm run validate:repository && pnpm run release:prepare"
  || scripts["check:no-tests"] !== "./bin/development-system check-no-tests"
  || ["test", "test:acceptance", "measure:test"].some(name => name in scripts)
  || Object.values(scripts).some(command => /node\s+--test\b/.test(String(command)))
  || !pkg.files.includes("claude/") || !pkg.files.includes("runtime/")) {
  throw new Error(`package.json release metadata does not match ${version} / catalog ${catalogVersion}`);
}
console.log(JSON.stringify({ version, previous, catalogVersion, previousArtifacts: previousCount, repointed: updated.size, added: added.length, artifacts: manifest.artifacts.length, operation: write ? "write" : "check" }));

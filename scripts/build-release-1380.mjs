// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSkillCatalog } from "../src/skills.mjs";
import { directiveTestInstructions, findTestDirectives, TEST_FILE_PATTERNS } from "../src/test-change-policy.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.38.0", previous = "1.37.0", catalogVersion = "0.56.0";
const prefix = `artifacts/${version}`;
const args = process.argv.slice(2);
if (args.length !== 1 || !["--write", "--check"].includes(args[0])) throw new Error("Use --write or --check");
const write = args[0] === "--write";
const generated = [`manifests/${version}.json`, `catalog/${catalogVersion}.json`, `${prefix}/contract.md`];
if (write) for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) for (const path of [...generated, `${prefix}/refresh-provenance.json`]) {
  try { execFileSync("git", ["cat-file", "-e", `${ref}:${path}`], { cwd: root, stdio: "ignore" }); }
  catch { continue; }
  throw new Error(`Published ${path} is immutable; create a new version`);
}
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {boolean} condition @param {string} message */
function requireValid(condition, message) { if (!condition) throw new Error(`Release ${version}: ${message}`); }
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  requireValid(target.startsWith(`${root}/`), `output escapes root: ${path}`);
  if (write) { await mkdir(dirname(target), { recursive: true }); await writeFile(target, data, { mode: 0o644 }); }
  else requireValid((await bytes(path)).equals(Buffer.from(data)), `generated bytes drift: ${path}`);
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const output = [];
  for (const entry of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    requireValid(![".DS_Store", "__pycache__", "node_modules", "evals"].includes(entry.name) && !entry.name.endsWith(".pyc"), `local residue: ${path}`);
    if (entry.isDirectory()) output.push(...await files(path));
    else { requireValid(entry.isFile(), `nonregular source: ${path}`); output.push(path); }
  }
  return output.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const path of await files(directory)) digest.update(relative(directory, path)).update("\0").update(await bytes(path)).update("\0");
  return digest.digest("hex");
}
const oldManifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of oldManifest.artifacts) requireValid(artifact.sha256 === hash(await bytes(artifact.sourcePath)), `published input drift: ${artifact.sourcePath}`);
const oldCatalog = JSON.parse((await bytes("catalog/0.55.0.json")).toString());
requireValid((await validateSkillCatalog(oldCatalog, root)).length === 0, "previous catalog drift");
const provenance = JSON.parse((await bytes(`${prefix}/refresh-provenance.json`)).toString());
requireValid(provenance.contractVersion === version && provenance.catalogVersion === catalogVersion, "provenance version mismatch");
requireValid(new Set(provenance.managed.map((/** @type {any} */ row) => row.name)).size === provenance.managed.length, "duplicate refresh names");
const catalog = structuredClone(oldCatalog);
catalog.catalogVersion = catalogVersion;
for (const row of provenance.managed) {
  const skill = catalog.skills.find((/** @type {any} */ s) => s.logicalName === row.name);
  requireValid(Boolean(skill), `unknown managed skill: ${row.name}`);
  const oldUpstream = skill.source.upstreamReference ?? (skill.source.repository !== "https://github.com/AO-HyS/development-system" ? skill.source : null);
  requireValid(Boolean(oldUpstream), `attempt to change AO-owned skill: ${row.name}`);
  requireValid(row.upstream.repository === oldUpstream.repository && row.upstream.package === oldUpstream.package, `upstream ownership changed: ${row.name}`);
  requireValid(row.upstream.package ? /^sha512-[A-Za-z0-9+/]+={0,2}$/.test(row.upstream.integrity) && /^\d+\.\d+\.\d+$/.test(row.upstream.version) : /^[a-f0-9]{40}$/.test(row.upstream.commit), `missing upstream revision: ${row.name}`);
  if (row.directory) {
    requireValid(row.directory === `${prefix}/skills/external/${row.name}`, `noncanonical refresh folder: ${row.name}`);
    const digest = await folderHash(row.directory);
    requireValid(digest === row.folderSha256, `refresh hash drift: ${row.name}`);
    skill.source = { repository: "https://github.com/AO-HyS/development-system", commit: "$INSTALL_COMMIT", path: row.directory, upstreamReference: row.upstream };
    for (const variant of skill.variants) { variant.sourceDirectory = row.directory; variant.folderSha256 = digest; }
  } else if (skill.source.upstreamReference) skill.source.upstreamReference = row.upstream;
  else skill.source = row.upstream;
}
requireValid(catalog.skills.length === oldCatalog.skills.length, "refresh must not add or remove capabilities");
for (const skill of catalog.skills) if (!provenance.managed.some((/** @type {any} */ row) => row.name === skill.logicalName)) {
  requireValid(JSON.stringify(skill) === JSON.stringify(oldCatalog.skills.find((/** @type {any} */ s) => s.logicalName === skill.logicalName)), `unowned skill changed: ${skill.logicalName}`);
}
await outputJson(`catalog/${catalogVersion}.json`, catalog);
const contract = (await bytes(`artifacts/${previous}/contract.md`)).toString()
  .replace(`# Development contract ${previous}`, `# Development contract ${version}`)
  .replace("The paired skill catalog is 0.55.0.", `The paired skill catalog is ${catalogVersion}.`)
  + `\n## ${version}: external capability refresh\n\nCatalog ${catalogVersion} refreshes installed third-party capabilities from recorded upstream commits while retaining AOHYS adapters, authorization, browser routing and the no-automated-tests rule. The Impeccable skill stays at released version 4.3.1; its engine is pinned separately to released engine 0.1.7 with asset hashes in refresh-provenance.json. AO-authored workflows remain unchanged. Upstream removals are reported as retained-last-available rather than silently mapped to different capabilities. This tooling update requires no application production deployment. Publication and product pin rollouts remain separate authorized operations. Editable standalone skills outside the catalog retain their own upstream lock and reversible install receipts. Provider-managed builtins and runtime bundles are not rewritten by this catalog.\n`;
await output(`${prefix}/contract.md`, contract);
const manifest = structuredClone(oldManifest);
manifest.contractVersion = version;
for (const artifact of manifest.artifacts) {
  if (artifact.logicalName === "development-contract") artifact.sourcePath = `${prefix}/contract.md`;
  if (artifact.logicalName === "skill-catalog") artifact.sourcePath = `catalog/${catalogVersion}.json`;
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
const errors = await validateSkillCatalog(catalog, root);
requireValid(errors.length === 0, errors.join("\n"));
const instructionPaths = new Set(manifest.artifacts.map((/** @type {any} */ a) => a.sourcePath));
for (const directory of new Set(catalog.skills.flatMap((/** @type {any} */ s) => s.variants.map((/** @type {any} */ v) => v.sourceDirectory)))) {
  for (const path of await files(/** @type {string} */ (directory))) instructionPaths.add(path);
}
for (const path of instructionPaths) {
  requireValid(!TEST_FILE_PATTERNS.some(pattern => pattern.test(/** @type {string} */ (path))), `automated test file: ${path}`);
  const data = await bytes(/** @type {string} */ (path));
  if (data.includes(0)) continue;
  const text = data.toString();
  requireValid(!/^(?:<{7}|={7}|>{7})/m.test(text), `merge conflict marker: ${path}`);
  requireValid(!/\bVeredicto\b|Preguntas al margen|Qué cambió|Known issues\*{0,2} table/i.test(text), `retired report instruction: ${path}`);
  // Production lint detection necessarily names banned mocking frameworks; it is not an agent instruction.
  const refreshed = provenance.managed.some((/** @type {any} */ row) => row.directory && String(path).startsWith(`${row.directory}/`));
  // Reused published policy/runtime sources retain the previous gardener scope:
  // JSON policy literals can name forbidden commands precisely to block them.
  if ((refreshed || /\.(md|toml|ya?ml)$/.test(String(path))) && !String(path).endsWith("/assets/anti-slop/rules/no-module-mocking.ts")) {
    requireValid(findTestDirectives(text, directiveTestInstructions).length === 0, `automated test instruction: ${path}`);
  }
}
const pkg = JSON.parse((await bytes("package.json")).toString());
requireValid(pkg.version === version && pkg.contractVersion === version && pkg.scripts["release:prepare"] === "node ./scripts/build-release-1380.mjs --check", "package metadata mismatch");
requireValid(pkg.scripts["skills:audit"].includes(`--version ${catalogVersion}`) && pkg.scripts["skills:sync"].includes(`--version ${catalogVersion}`), "catalog script mismatch");
const guard = (await bytes("src/guardrails.mjs")).toString();
requireValid(guard.includes(`const guardCatalogVersion = "${catalogVersion}"`) && guard.includes(`const guardSetupVersion = "${version}"`), "guard pins mismatch");
await outputJson(`manifests/${version}.json`, manifest);
console.log(JSON.stringify({ version, previous, catalogVersion, managedSources: provenance.managed.length, changedDirectories: provenance.managed.filter((/** @type {any} */ row) => row.directory).length, artifacts: manifest.artifacts.length, operation: write ? "write" : "check", deploymentRequired: false }));

// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.27.4", previous = "1.27.3", prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some(arg => !["--write", "--check"].includes(arg)) || write && process.argv.includes("--check")) throw new Error("Use --write or --check");
if (write) {
  for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
    let published = false;
    try { execFileSync("git", ["cat-file", "-e", `${ref}:manifests/${version}.json`], { cwd: root, stdio: "ignore" }); published = true; } catch {}
    if (published) throw new Error(`Published ${version} is immutable; create a new version`);
  }
}
/** @param {string|Buffer} bytes */
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  if (write) { await mkdir(dirname(resolve(root, path)), { recursive: true }); await writeFile(resolve(root, path), data); }
  else if (!(await bytes(path)).equals(Buffer.from(data))) throw new Error(`Generated bytes drift: ${path}`);
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
manifest.contractVersion = version;
const sources = [];
for (const name of (await readdir(resolve(root, "runtime/jev-governance"))).sort()) {
  if (!name.endsWith(".mjs")) throw new Error(`Unexpected runtime file: ${name}`);
  const sourcePath = `runtime/jev-governance/${name}`;
  const artifactPath = `${prefix}/governance-runtime/${name}`;
  const data = await bytes(sourcePath);
  await output(artifactPath, data);
  sources.push({ sourcePath, artifactPath, destination: `.codex/development-system/governance-runtime/${name}`, sha256: hash(data) });
}
await outputJson(`${prefix}/source-provenance.json`, { schemaVersion: 1, contractVersion: version, mode: "parent-owned-governance", previousContract: previous, decision: "docs/adr/0053-passive-governance-contention.md", legacyController: "disabled", advisoryRuntime: "unchanged-compatible-1.24.0" });
await outputJson(`${prefix}/runtime-source-provenance.json`, { schemaVersion: 1, contractVersion: version, activeMode: "parent-owned-governance", sources, operationalEvidence: "Isolated regression and installation checks do not establish live host enforcement. Current operational probes are required." });
const contract = (await bytes(`artifacts/${previous}/contract.md`)).toString() + "\n## Passive host contention repair (1.27.4)\n\nUnchanged observed host identities reuse their validated stored observation without taking the global registry mutex. New or changed identities recheck and commit under the existing process-owned lock. Passive shell capability discovery uses an explicit exact pwd probe; ordinary shell invocations no longer create passive registry records. Supported non-shell observation pairs, governed permissions, ownership, required Jev judgments, bounded lock waits and independent acceptance remain unchanged. Historical registry and receipts are preserved. Maintenance follows ADR 0048 and does not claim that a defective runtime certifies its own repair.\n";
await output(`${prefix}/contract.md`, contract);
for (const artifact of manifest.artifacts) {
  const runtime = sources.find(item => item.destination === artifact.destination);
  const replacement = runtime?.artifactPath ?? ({
    "development-contract": `${prefix}/contract.md`,
    "orchestration-source-provenance": `${prefix}/source-provenance.json`,
    "orchestration-runtime-provenance": `${prefix}/runtime-source-provenance.json`,
  })[/** @type {string} */ (artifact.logicalName)];
  if (replacement) { artifact.sourcePath = replacement; artifact.sha256 = hash(await bytes(replacement)); }
  else if (artifact.sha256 !== hash(await bytes(artifact.sourcePath))) throw new Error(`Published source drift: ${artifact.sourcePath}`);
}
if (sources.length !== 14 || manifest.artifacts.length !== 61 || sources.some(item => !manifest.artifacts.some((/** @type {any} */ artifact) => artifact.sourcePath === item.artifactPath))) throw new Error("Runtime or manifest inventory is incomplete");
await outputJson(`manifests/${version}.json`, manifest);
console.log(JSON.stringify({ version, catalogVersion: "0.46.1", artifacts: manifest.artifacts.length, runtimeFiles: sources.length, operation: write ? "write" : "check" }));

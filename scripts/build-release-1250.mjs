// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateSkillCatalog } from "../src/skills.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.25.0", catalogVersion = "0.45.0", prefix = `artifacts/${version}`;
const write = process.argv.includes("--write");
if (process.argv.slice(2).some((arg) => !["--write", "--check"].includes(arg)) || write && process.argv.includes("--check")) throw new Error("Use --write or --check");
if (write) {
  let published = false;
  try { execFileSync("git", ["cat-file", "-e", `HEAD:manifests/${version}.json`], { cwd: root, stdio: "ignore" }); published = true; } catch { /* Candidate only. */ }
  if (published) throw new Error(`Recorded ${version} is immutable; create a new version`);
}
/** @param {Buffer|string} value */
const hash = (value) => createHash("sha256").update(value).digest("hex");
/** @param {string} path */
const bytes = (path) => readFile(resolve(root, path));
/** @param {string} path */
const json = async (path) => JSON.parse((await bytes(path)).toString());
/** @param {string} path @param {unknown} value */
async function output(path, value) {
  const data = JSON.stringify(value, null, 2) + "\n";
  if (write) { await mkdir(dirname(resolve(root, path)), { recursive: true }); await writeFile(resolve(root, path), data); }
  else if ((await bytes(path)).toString() !== data) throw new Error(`Generated bytes drift: ${path}`);
}
/** @param {string} directory */
async function files(directory) {
  /** @type {string[]} */ const result = [];
  /** @param {string} path */
  async function walk(path) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const full = resolve(path, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) result.push(full);
      else throw new Error(`Nonregular release source: ${full}`);
    }
  }
  await walk(resolve(root, directory));
  return result.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const file of await files(directory)) digest.update(relative(resolve(root, directory), file)).update("\0").update(await readFile(file)).update("\0");
  return digest.digest("hex");
}

const catalog = await json("catalog/0.44.0.json");
catalog.catalogVersion = catalogVersion;
const skillNames = ["coding-orchestration", "orchestrate-work", "implement-spec", "flow-implement", "drive-development-flow", "working-backwards", "grill-with-docs"];
for (const name of skillNames) {
  const skill = catalog.skills.find((/** @type {any} */ item) => item.logicalName === name);
  if (!skill) throw new Error(`Missing catalog skill ${name}`);
  const directory = `${prefix}/skills/internal/${name}`;
  skill.source = { repository: "https://github.com/AO-HyS/development-system", commit: "$INSTALL_COMMIT", path: directory };
  for (const variant of skill.variants) { variant.sourceDirectory = directory; variant.folderSha256 = await folderHash(directory); }
}
const catalogErrors = await validateSkillCatalog(catalog, root);
if (catalogErrors.length) throw new Error(catalogErrors.join("\n"));
await output(`catalog/${catalogVersion}.json`, catalog);

const sources = [];
for (const source of await files("runtime/jev-governance")) {
  if (!source.endsWith(".mjs")) throw new Error(`Unexpected runtime file: ${source}`);
  const file = relative(resolve(root, "runtime/jev-governance"), source);
  const artifactPath = `${prefix}/governance-runtime/${file}`;
  if (write) { await mkdir(dirname(resolve(root, artifactPath)), { recursive: true }); await copyFile(source, resolve(root, artifactPath)); }
  const sha256 = hash(await bytes(artifactPath));
  if (sha256 !== hash(await readFile(source))) throw new Error(`Runtime snapshot drift: ${file}`);
  sources.push({ sourcePath: relative(root, source), artifactPath, destination: `.codex/development-system/governance-runtime/${file}`, sha256 });
}
if (sources.length < 8) throw new Error("Governance runtime incomplete");
await output(`${prefix}/source-provenance.json`, { schemaVersion: 1, contractVersion: version, mode: "parent-owned-governance", previousContract: "1.24.0", decision: "docs/adr/0047-whole-flow-jev-governance.md", legacyController: "disabled", advisoryRuntime: "unchanged-compatible-1.24.0" });
await output(`${prefix}/runtime-source-provenance.json`, { schemaVersion: 1, contractVersion: version, activeMode: "parent-owned-governance", sources, operationalEvidence: "Installation hashes are not host enforcement; consult release validation evidence and capability matrix." });
const manifest = await json("manifests/1.24.0.json");
manifest.contractVersion = version;
/** @type {Record<string,string>} */
const replacements = {
  "development-contract": `${prefix}/contract.md`,
  "personal-codex-instructions": `${prefix}/global-codex-instructions.md`,
  "model-routing": `${prefix}/model-routing.md`,
  "agent-roster": `config/${version}/agent-roster.json`,
  "skill-catalog": `catalog/${catalogVersion}.json`,
  "orchestration-contract": `${prefix}/orchestration-contract.md`,
  "orchestration-source-provenance": `${prefix}/source-provenance.json`,
  "orchestration-runtime-provenance": `${prefix}/runtime-source-provenance.json`,
  "orchestration-runtime-scripts-run-jev-workflow-mjs": `${prefix}/legacy-controller-disabled.mjs`,
};
for (const artifact of manifest.artifacts) {
  const previous = artifact.sourcePath;
  if (artifact.logicalName.startsWith("codex-agent-")) artifact.sourcePath = `${prefix}/agents/codex/${previous.split("/").at(-1)}`;
  else if (replacements[artifact.logicalName]) artifact.sourcePath = replacements[artifact.logicalName];
  const digest = hash(await bytes(artifact.sourcePath));
  if (previous === artifact.sourcePath && digest !== artifact.sha256) throw new Error(`Immutable published source drift: ${artifact.id}`);
  artifact.sha256 = digest;
}
for (const item of sources) {
  const logicalName = `governance-runtime-${relative("runtime/jev-governance", item.sourcePath).replaceAll(/[^a-zA-Z0-9]/g, "-")}`;
  manifest.artifacts.push({ id: `${logicalName}.codex`, logicalName, sourcePath: item.artifactPath, destination: item.destination, harness: "codex", sha256: item.sha256, expectedMirrorOf: null });
}
const policyPath = `config/${version}/orchestration-policy.json`;
manifest.artifacts.push({ id: "governance-policy.codex", logicalName: "governance-policy", sourcePath: policyPath, destination: ".codex/development-system/governance-policy.json", harness: "codex", sha256: hash(await bytes(policyPath)), expectedMirrorOf: null });
if (new Set(manifest.artifacts.map((/** @type {any} */ artifact) => artifact.destination)).size !== manifest.artifacts.length) throw new Error("Duplicate managed destination");
await output(`manifests/${version}.json`, manifest);
console.log(JSON.stringify({ version, catalogVersion, artifacts: manifest.artifacts.length, runtimeFiles: sources.length, operation: write ? "write" : "check" }));

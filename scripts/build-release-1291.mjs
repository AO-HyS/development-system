// @ts-check
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const version = "1.29.1";
const write = process.argv.includes("--write");
if (process.argv.slice(2).some((arg) => !["--write", "--check"].includes(arg)) || (write && process.argv.includes("--check"))) {
  throw new Error("Use --write or --check");
}
if (write) {
  for (const ref of ["refs/remotes/origin/main", `refs/tags/v${version}`]) {
    try {
      execFileSync("git", ["cat-file", "-e", `${ref}:manifests/${version}.json`], { cwd: root, stdio: "ignore" });
      throw new Error(`Published manifests/${version}.json is immutable; create a new version`);
    } catch (error) {
      if (error instanceof Error && error.message.startsWith("Published")) throw error;
    }
  }
}
/** @param {string} path */
const bytes = (path) => readFile(resolve(root, path));
/** @param {string|Buffer} data */
const hash = (data) => createHash("sha256").update(data).digest("hex");
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  if (write) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data);
  } else if (!(await readFile(target)).equals(Buffer.from(data))) {
    throw new Error(`Generated bytes drift: ${path}`);
  }
}

const source = (await bytes("artifacts/1.29.0/contract.md")).toString();
const contract = source.replace("# Development contract 1.29.0", "# Development contract 1.29.1")
  + "\n## Repository preparation correction\n\nInitialize and normalize generate the advisory repository adapter. Product-specific lifecycle extensions survive normalization; shared lifecycle policy comes from this version. The unchanged skill catalog remains 0.48.0.\n";
const contractPath = `artifacts/${version}/contract.md`;
await output(contractPath, contract);
const manifest = JSON.parse((await bytes("manifests/1.29.0.json")).toString());
manifest.contractVersion = version;
const artifact = manifest.artifacts.find((/** @type {{logicalName:string}} */ item) => item.logicalName === "development-contract");
if (!artifact) throw new Error("Missing development-contract artifact");
artifact.sourcePath = contractPath;
artifact.sha256 = hash(contract);
for (const item of manifest.artifacts) {
  if (item !== artifact && hash(await bytes(item.sourcePath)) !== item.sha256) throw new Error(`Published source drift: ${item.sourcePath}`);
}
await output(`manifests/${version}.json`, JSON.stringify(manifest, null, 2) + "\n");
console.log(JSON.stringify({ version, catalogVersion: "0.48.0", artifacts: manifest.artifacts.length, operation: write ? "write" : "check" }));

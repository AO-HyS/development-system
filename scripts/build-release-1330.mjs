/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  if (!target.startsWith(`${root}/`)) throw new Error(`Release output escapes root: ${path}`);
  if (write) {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, data, { mode: 0o644 });
  } else if (!(await bytes(path)).equals(Buffer.from(data))) {
    throw new Error(`Generated bytes drift: ${path}`);
  }
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {string} text @param {string} from @param {string} to */
function replaceOnce(text, from, to) {
  if (text.split(from).length !== 2) throw new Error(`Expected one occurrence of: ${from.slice(0, 70)}`);
  return text.replace(from, to);
}
/** @param {boolean} condition @param {string} message */
function assert(condition, message) {
  if (!condition) throw new Error(`Release ${version} source check failed: ${message}`);
}
/** @param {string} directory */
async function files(directory) {
  /** @type {string[]} */ const result = [];
  /** @param {string} path */
  async function walk(path) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      const full = resolve(path, entry.name);
      if (["__pycache__", ".DS_Store", "node_modules"].includes(entry.name) || entry.name.endsWith(".pyc")) {
        throw new Error(`Generated or local entry in hashed release source: ${full}`);
      }
      if (entry.isDirectory()) await walk(full);
      else if (entry.isFile()) result.push(full);
      else throw new Error(`Nonregular release source: ${full}`);
    }
  }
  await walk(resolve(root, directory));
  return result.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const file of await files(directory)) digest.update(relative(resolve(root, directory), file)).update("\0").update(await readFile(file)).update("\0");
  return digest.digest("hex");
}


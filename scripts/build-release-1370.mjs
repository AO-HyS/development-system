/** @param {string|Buffer} data */
const hash = data => createHash("sha256").update(data).digest("hex");
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {boolean} condition @param {string} message */
function assert(condition, message) { if (!condition) throw new Error(`Release ${version}: ${message}`); }
/** @param {string} path @param {string|Buffer} data */
async function output(path, data) {
  const target = resolve(root, path);
  assert(target.startsWith(`${root}/`), `output escapes root: ${path}`);
  if (write) { await mkdir(dirname(target), { recursive: true }); await writeFile(target, data, { mode: 0o644 }); }
  else assert((await bytes(path)).equals(Buffer.from(data)), `generated bytes drift: ${path}`);
}
/** @param {string} path @param {unknown} value */
const outputJson = (path, value) => output(path, JSON.stringify(value, null, 2) + "\n");
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const entries = await readdir(resolve(root, directory), { withFileTypes: true });
  const result = await Promise.all(entries.map(entry => {
    assert(![".DS_Store", "__pycache__", "node_modules"].includes(entry.name) && !entry.name.endsWith(".pyc"), `local file in release: ${directory}/${entry.name}`);
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) return files(path);
    assert(entry.isFile(), `nonregular release source: ${path}`);
    return Promise.resolve([path]);
  }));
  return result.flat().sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash("sha256");
  for (const path of await files(directory)) digest.update(relative(directory, path)).update("\0").update(await bytes(path)).update("\0");
  return digest.digest("hex");
}
/** Migrate selected active surfaces only; published inputs remain unchanged.
 * @param {string} text */
function migrate(text) {
  return text.replace(/gpt-6-astra/g, "gpt-6.1-sol").replace(/gpt-6-sol/g, "gpt-6.1-sol")
    .replace(/Astra\s+6\s+XHigh/g, "Sol 6.1 High").replace(/Astra\s+XHigh/g, "Sol 6.1 High")
    .replace(/Astra/g, "Sol 6.1").replace(/Sol 6 (High|Medium)/g, "Sol 6.1 $1")
    .replace(/\bXHigh\b/g, "High").replace(/\bxhigh\b/g, "high");
}

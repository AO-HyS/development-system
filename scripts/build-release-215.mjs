// @ts-check
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSkillCatalog } from '../src/skills.mjs';
import { checkRolePolicyOutputs, renderHostInstructions } from '../src/role-policy.mjs';
import { checkActiveToolingDocs } from './check-active-tooling-docs.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = '2.1.5', previous = '2.1.4', catalogVersion = '0.65.0', previousCatalog = '0.64.0', prefix = `artifacts/${version}`;
const external = [
  'emil-animate', 'animate-expo', 'animation-performance', 'apple-design', 'ask-sonner', 'break-ui', 'emil-design-eng',
  'find-animation-opportunities', 'improve-animations', 'mobile-native', 'pick-ui-library', 'emil-prototype',
  'review-animations', 'write-swift', 'good-css',
];
const upstreams = /** @type {Record<string, {repository:string, commit:string}>} */ ({
  emil: { repository: 'https://github.com/emilkowalski/skills', commit: '2d228630ba1446365f614a108cb8252f1feda202' },
  css: { repository: 'https://github.com/vojtaholik/good-css', commit: '92d436ba1937d1b1407c47e35abb3e199eaace2e' },
});
const mode = process.argv[2];
if (process.argv.length !== 3 || !['--write', '--check'].includes(mode)) throw new Error('Use --write or --check');
/** @param {string|Buffer} value */
const hash = value => createHash('sha256').update(value).digest('hex');
/** @param {string} path */
const bytes = path => readFile(resolve(root, path));
/** @param {string} path @param {string|Buffer} value */
async function output(path, value) {
  if (mode === '--check') {
    if (!(await bytes(path)).equals(Buffer.from(value))) throw new Error(`Generated bytes drift: ${path}`);
    return;
  }
  for (const ref of ['refs/remotes/origin/main', `refs/tags/v${version}`]) {
    try { execFileSync('git', ['cat-file', '-e', `${ref}:${path}`], { cwd: root, stdio: 'ignore' }); } catch { continue; }
    throw new Error(`Published ${path} is immutable; create a new version`);
  }
  await mkdir(dirname(resolve(root, path)), { recursive: true });
  await writeFile(resolve(root, path), value);
}
/** @param {string} directory @returns {Promise<string[]>} */
async function files(directory) {
  const result = [];
  for (const entry of await readdir(resolve(root, directory), { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await files(path));
    else if (entry.isFile()) result.push(path);
    else throw new Error(`Nonregular skill source: ${path}`);
  }
  return result.sort();
}
/** @param {string} directory */
async function folderHash(directory) {
  const digest = createHash('sha256');
  for (const path of await files(directory)) digest.update(relative(directory, path)).update('\0').update(await bytes(path)).update('\0');
  return digest.digest('hex');
}
/** Shared global instructions: canonical body plus the generated host sections. */
async function globalInstructions() {
  const body = (await bytes('config/global-instructions.md')).toString();
  for (const marker of ['{{shared-host-rules}}', '{{codex-host}}', '{{claude-host}}']) if (!body.includes(marker)) throw new Error(`Missing ${marker}`);
  return body.replace('{{shared-host-rules}}', renderHostInstructions('shared').trimEnd())
    .replace('{{codex-host}}', renderHostInstructions('codex').trimEnd())
    .replace('{{claude-host}}', renderHostInstructions('claude').trimEnd());
}
const hostProfiles = () => ['shared', 'codex', 'claude'].map(host => renderHostInstructions(/** @type {'shared'|'codex'|'claude'} */ (host)).trimEnd()).join('\n\n');

const releaseNote = `## ${version}: shared host rules, rule floors and design skills

Contract ${version} renders the shared global instructions from config/global-instructions.md: the rules both hosts follow appear once under Shared host rules, and the Codex and Claude Code host sections keep only host-specific lines. ~/.claude/rules/orchestration.md becomes a pointer, so Claude Code no longer loads its host section twice. \`development-system check-agents-rules --base <ref> [--head <ref>] <file>\` lists every behavior-constraining sentence of a base AGENTS.md/CLAUDE.md that no tracked document still carries; \`development-system check-lint-floor --write <snapshot>\` on the base checkout and \`--snapshot <snapshot>\` on the candidate list lint rules a migration dropped or downgraded from error to warning. Both exit 1 until each finding is restored or explicitly allowed. Catalog ${catalogVersion} adds Emil Kowalski's design and motion skills (animate and prototype install as emil-animate and emil-prototype beside the existing skills of those names) and Vojta Holik's good-css, each with pinned upstream provenance, and moves implement-spec to a ${version} copy built on Matt Pocock's task-graph flow without tests or mandatory worktrees. Installed files do not prove that a harness selects these skills; that needs observed-session evidence.
`;

const roleCheck = checkRolePolicyOutputs(root);
if (!roleCheck.valid) throw new Error(roleCheck.errors.join('; '));
const manifest = JSON.parse((await bytes(`manifests/${previous}.json`)).toString());
for (const artifact of manifest.artifacts) {
  if (hash(await bytes(artifact.sourcePath)) !== artifact.sha256) throw new Error(`Previous artifact drift: ${artifact.sourcePath}`);
}
const catalog = JSON.parse((await bytes(`catalog/${previousCatalog}.json`)).toString());
catalog.catalogVersion = catalogVersion;
for (const name of external) {
  if (catalog.skills.some((/** @type {{logicalName:string}} */ row) => row.logicalName === name)) throw new Error(`Skill already exists: ${name}`);
  const directory = `${prefix}/skills/external/${name}`;
  const provenance = JSON.parse((await bytes(`${directory}/upstream.json`)).toString());
  const expected = upstreams[name === 'good-css' ? 'css' : 'emil'];
  if (provenance.repository !== expected.repository || provenance.commit !== expected.commit) throw new Error(`Unexpected upstream: ${name}`);
  const digest = await folderHash(directory);
  catalog.skills.push({
    logicalName: name,
    physicalHarnesses: ['codex', 'claude'],
    source: {
      repository: 'https://github.com/AO-HyS/development-system', commit: '$INSTALL_COMMIT', path: directory,
      upstreamReference: { repository: provenance.repository, license: 'MIT', commit: provenance.commit,
        path: provenance.path, capabilityTreeSha256: provenance.capabilityTreeSha256 },
    },
    variants: [
      { id: `${name}.codex`, harness: 'codex', sourceDirectory: directory, destination: `.agents/skills/${name}`, folderSha256: digest, expectedMirrorOf: null },
      { id: `${name}.claude`, harness: 'claude', sourceDirectory: directory, destination: `.claude/skills/${name}`, folderSha256: digest, expectedMirrorOf: `${name}.codex`, install: 'symlink' },
    ],
  });
}
const implementSpec = catalog.skills.find((/** @type {{logicalName:string}} */ row) => row.logicalName === 'implement-spec');
if (!implementSpec) throw new Error('implement-spec missing from catalog');
const specDirectory = `${prefix}/skills/internal/implement-spec`;
implementSpec.source.path = specDirectory;
for (const variant of implementSpec.variants) { variant.sourceDirectory = specDirectory; variant.folderSha256 = await folderHash(specDirectory); }
const errors = await validateSkillCatalog(catalog, root);
if (errors.length) throw new Error(errors.join('; '));
await output(`catalog/${catalogVersion}.json`, JSON.stringify(catalog, null, 2) + '\n');

manifest.contractVersion = version;
for (const artifact of manifest.artifacts) {
  const name = artifact.logicalName;
  if (name === 'skill-catalog') artifact.sourcePath = `catalog/${catalogVersion}.json`;
  if (name === 'agent-roster') {
    artifact.sourcePath = `config/${version}/agent-roster.json`;
    await output(artifact.sourcePath, await bytes('config/agent-roster.json'));
  }
  if (name === 'claude-rule-orchestration-md') {
    artifact.sourcePath = `${prefix}/claude/rules/orchestration.md`;
    await output(artifact.sourcePath, await bytes('claude/rules/orchestration.md'));
  }
  if (name === 'personal-codex-instructions') {
    artifact.sourcePath = `${prefix}/global-codex-instructions.md`;
    await output(artifact.sourcePath, await globalInstructions());
  }
  if (['development-contract', 'orchestration-contract', 'model-routing'].includes(name)) {
    const original = (await bytes(artifact.sourcePath)).toString();
    const hostStart = original.indexOf('\n## Generated host role profiles');
    const browserStart = original.indexOf('\n## Browser resource preparation');
    if (hostStart < 0) throw new Error(`Missing generated host guidance: ${name}`);
    const suffix = browserStart > hostStart ? original.slice(browserStart) : '';
    let current = original.slice(0, hostStart).replaceAll(previous, version).replaceAll(previousCatalog, catalogVersion);
    if (name === 'development-contract') current = current.trimEnd() + '\n\n' + releaseNote;
    const filename = name === 'development-contract' ? 'contract' : name;
    artifact.sourcePath = `${prefix}/${filename}.md`;
    await output(artifact.sourcePath, (current.trimEnd() + '\n\n## Generated host role profiles\n\n' + hostProfiles() + '\n' + suffix).trimEnd() + '\n');
  }
  artifact.sha256 = hash(await bytes(artifact.sourcePath));
}
await output(`manifests/${version}.json`, JSON.stringify(manifest, null, 2) + '\n');
const pkg = JSON.parse((await bytes('package.json')).toString());
if (pkg.version !== version || pkg.contractVersion !== version) throw new Error('Package version mismatch');
await checkActiveToolingDocs();
console.log(JSON.stringify({ version, previous, catalogVersion, addedSkills: external, updatedSkills: ['implement-spec'], operation: mode }));
